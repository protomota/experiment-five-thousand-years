import assert from 'node:assert/strict';
import * as THREE from 'three';
import {createGlobeFlight,isGlobeDestinationVisible,sampleGlobeFlight} from '../src/globe-flight.ts';
const start=new THREE.Vector3(1.04,0,0),end=new THREE.Vector3(0,0,-1.06);
const flight=createGlobeFlight(start,end),point=new THREE.Vector3();
const at=progress=>sampleGlobeFlight(flight,end,progress,point).clone();
assert(at(0).distanceTo(start)<1e-9,'Begins at current camera position');
assert(at(.15).length()>start.length(),'Pulls back before travel');
assert(at(.15).angleTo(start)<1e-6,'Holds origin during pullback');
assert(Math.abs(at(.5).length()-flight.peakDistance)<1e-9,'Travels at elevated distance');
assert(at(.8).angleTo(end)<1e-6,'Arrives over destination before descending');
assert(at(.8).length()>at(.95).length(),'Zooms into destination');
assert(at(1).distanceTo(end)<1e-9,'Finishes exactly at destination');
const nearby=createGlobeFlight(start,new THREE.Vector3(1,.03,0).setLength(1.04));
assert(nearby.peakDistance<flight.peakDistance,'Nearby travel uses a smaller pullback');
const stationary=createGlobeFlight(start,start);
assert(sampleGlobeFlight(stationary,start,.5,point).distanceTo(start)<1e-9,'Same-place selection does not fly out');
const interrupted=at(.45),replacement=new THREE.Vector3(0,1.04,0);
assert(sampleGlobeFlight(createGlobeFlight(interrupted,replacement),replacement,0,point).distanceTo(interrupted)<1e-9,'Retargeting begins at current position without a jump');
const camera=new THREE.PerspectiveCamera(35,1.5,.001,100);camera.position.set(1.22,0,0);camera.lookAt(0,0,0);
const visible=new THREE.Vector3(1,.025,0).normalize().multiplyScalar(1.12);
assert(isGlobeDestinationVisible(camera,visible),'Visible destination uses direct travel');
assert(!isGlobeDestinationVisible(camera,new THREE.Vector3(-1,0,0)),'Back side of globe is not visible');
assert(!isGlobeDestinationVisible(camera,new THREE.Vector3(1,.3,0)),'Front-facing destination outside the viewport is not visible');
const direct=createGlobeFlight(camera.position,visible,true);
let previousRadius=camera.position.length();
for(let step=0;step<=100;step++){const sample=sampleGlobeFlight(direct,visible,step/100,point);assert(sample.length()<=previousRadius+1e-9,'Visible destination never pulls back while zooming in');previousRadius=sample.length();}
assert(point.distanceTo(visible)<1e-9,'Direct travel reaches the closer destination');
const farther=visible.clone().setLength(1.6);
for(const progress of [0,.2,.5,.8,1])assert(Math.abs(sampleGlobeFlight(direct,farther,progress,point).length()-1.22)<1e-9,'A wider area cannot zoom out a direct move');
console.log('PASS: staged flights, visible-destination direct travel, inward-only zoom, offscreen detection, and interrupted-flight continuity.');
